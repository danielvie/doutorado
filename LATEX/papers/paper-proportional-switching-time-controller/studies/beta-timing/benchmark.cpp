using Clock = std::chrono::steady_clock;
constexpr int single_count = 10000;
constexpr int batch_count = 500;
constexpr int batch_size = 200;
constexpr int warmup_count = 5000;
volatile double sink = 0;

struct Case {
    Input<double> d;
    Input<float> f;
    Result<double> expected;
};

static void require(bool valid, const char* message) {
    if (!valid) throw std::runtime_error(message);
}

static std::vector<Case> load(const std::string& path) {
    std::ifstream file(path);
    require(file.good(), "Cannot open input CSV");
    std::string line;
    std::getline(file, line); // Header generated by run.py.
    std::vector<Case> data;
    while (std::getline(file, line)) {
        if (line.empty()) continue;
        std::stringstream row(line);
        std::string value;
        std::vector<double> values;
        while (std::getline(row, value, ',')) values.push_back(std::stod(value));
        require(values.size() == 37, "Wrong input CSV width");
        Case c;
        std::size_t k = 0;
        ++k; // cycle ID
        c.expected.beta = values[k++];
        for (std::size_t i = 0; i <= intervals; ++i) {
            const double us = values[k++];
            c.d.nominal[i] = us * 1e-6;
            c.f.nominal[i] = static_cast<float>(us);
        }
        for (std::size_t i = 0; i < offsets; ++i) {
            const double us = values[k++];
            c.d.raw[i] = us * 1e-6;
            c.f.raw[i] = static_cast<float>(us);
        }
        for (auto& x : c.expected.applied) x = values[k++] * 1e-6;
        for (auto& x : c.expected.dwell) x = values[k++] * 1e-6;
        c.d.bound = 3e-6;
        c.f.bound = 3.0f;
        data.push_back(c);
    }
    require(data.size() == 100, "Expected 100 saved article cycles");
    return data;
}

static void validate(const std::vector<Case>& data) {
    double max_double_beta_error = 0, max_float_beta_error = 0;
    double max_double_time_error_s = 0, max_float_time_error_us = 0;
    for (const auto& c : data) {
        const auto d = conditioner_double(c.d);
        const auto f = conditioner_float(c.f);
        max_double_beta_error = std::max(max_double_beta_error, std::abs(d.beta - c.expected.beta));
        max_float_beta_error = std::max(max_float_beta_error, std::abs(double(f.beta) - c.expected.beta));
        require(std::abs(beta_double(c.d) - d.beta) < 1e-12, "Double kernel mismatch");
        require(std::abs(double(beta_float(c.f) - f.beta)) < 1e-6, "Float kernel mismatch");
        for (std::size_t i = 0; i < offsets; ++i) {
            max_double_time_error_s = std::max(max_double_time_error_s, std::abs(d.applied[i] - c.expected.applied[i]));
            max_float_time_error_us = std::max(max_float_time_error_us, std::abs(double(f.applied[i]) - c.expected.applied[i] * 1e6));
        }
        for (std::size_t i = 0; i < intervals; ++i) {
            max_double_time_error_s = std::max(max_double_time_error_s, std::abs(d.dwell[i] - c.expected.dwell[i]));
            max_float_time_error_us = std::max(max_float_time_error_us, std::abs(double(f.dwell[i]) - c.expected.dwell[i] * 1e6));
        }
    }
    require(max_double_beta_error < 1e-12, "Double beta differs from article");
    require(max_float_beta_error < 1e-6, "Float beta differs from article");
    require(max_double_time_error_s < 1e-14, "Double schedule differs from article");
    require(max_float_time_error_us < 1e-3, "Float schedule differs from article");
    auto zero = data.front().d;
    zero.raw.fill(0);
    require(beta_double(zero) == 1, "Zero action must have beta one");
    // Binary-exact nominal dwells make the zero-margin boundary test exact.
    const double exact_dwell = std::ldexp(1.0, -18);
    for (std::size_t i = 0; i <= intervals; ++i) zero.nominal[i] = double(i) * exact_dwell;
    zero.bound = exact_dwell;
    zero.raw[0] = -1e-6;
    require(beta_double(zero) == 0, "No first-dwell margin must force beta zero");
    zero.raw.fill(0);
    zero.raw.back() = 1e-6;
    require(beta_double(zero) == 0, "No final-dwell margin must force beta zero");
    auto invalid = data.front().d;
    invalid.nominal[1] = 1e-6;
    bool rejected = false;
    try { (void)conditioner_double(invalid); } catch (const std::runtime_error&) { rejected = true; }
    require(rejected, "Invalid nominal schedule was not rejected");
    std::cout << std::setprecision(17) << "Validated " << data.size() << " cases. max_double_beta_error="
              << max_double_beta_error << " max_float_beta_error=" << max_float_beta_error
              << " max_double_time_error_s=" << max_double_time_error_s
              << " max_float_time_error_us=" << max_float_time_error_us << '\n';
}

static Clock::time_point timestamp() {
    std::atomic_signal_fence(std::memory_order_seq_cst);
    const auto time = Clock::now();
    std::atomic_signal_fence(std::memory_order_seq_cst);
    return time;
}

static double consume(double x) { return x; }
static double consume(float x) { return x; }
template <typename T> static double consume(const Result<T>& out) {
    double sum = out.beta;
    for (auto x : out.applied) sum += x;
    for (auto x : out.dwell) sum += x;
    return sum;
}

static void write(std::ostream& file, const std::string& name, const std::string& group,
                  const std::string& measurement, const std::vector<double>& times, int calls) {
    for (std::size_t i = 0; i < times.size(); ++i)
        file << name << ',' << group << ',' << measurement << ',' << i + 1 << ',' << calls
             << ',' << times[i] << ',' << times[i] / calls << '\n';
}

template <typename Function, typename Select>
static void measure(std::ostream& file, const std::string& name,
                    const std::vector<Case>& data, Function function, Select select) {
    double checksum = 0;
    for (int i = 0; i < warmup_count; ++i)
        checksum += consume(function(select(data[std::size_t(i) % data.size()])));
    sink = checksum;
    const std::array<std::string, 3> names = {"mixed_100", "conditioned_3", "unconditioned_97"};
    for (int group = 0; group < 3; ++group) {
        std::vector<const Case*> cases;
        for (const auto& c : data) {
            const bool conditioned = c.expected.beta < 1 - 1e-12;
            if (group == 0 || (group == 1 && conditioned) || (group == 2 && !conditioned))
                cases.push_back(&c);
        }
        require(cases.size() == (group == 0 ? 100 : group == 1 ? 3 : 97), "Wrong scenario size");
        std::vector<double> times(single_count);
        for (int i = 0; i < single_count; ++i) {
            const auto& input = select(*cases[std::size_t(i) % cases.size()]);
            const auto start = timestamp();
            const auto out = function(input);
            const auto stop = timestamp();
            checksum += consume(out); // Outside timer; all outputs observed.
            times[i] = std::chrono::duration<double, std::nano>(stop - start).count();
        }
        sink = checksum;
        write(file, name, names[group], "individual", times, 1);
        times.resize(batch_count);
        for (int batch = 0; batch < batch_count; ++batch) {
            double acc = 0;
            const auto start = timestamp();
            for (int j = 0; j < batch_size; ++j) {
                const auto& input = select(*cases[std::size_t(batch * batch_size + j) % cases.size()]);
                acc += consume(function(input));
            }
            const auto stop = timestamp();
            times[batch] = std::chrono::duration<double, std::nano>(stop - start).count();
            checksum += acc;
        }
        sink = checksum;
        write(file, name, names[group], "batch_mean", times, batch_size);
        std::cout << "Measured " << name << " / " << names[group] << '\n';
    }
    std::cout << "Checksum " << name << ": " << std::setprecision(17) << checksum << '\n';
}

int main(int argc, char** argv) {
    try {
        require(argc == 3, "Usage: benchmark INPUT.csv OUTPUT.csv");
        const auto data = load(argv[1]);
        validate(data);
        std::ofstream file(argv[2]);
        require(file.good(), "Cannot create output CSV");
        file << std::fixed << std::setprecision(9);
        file << "implementation,scenario,measurement,sample,calls,elapsed_ns,per_call_ns\n";
        std::cout << "steady_clock is_steady=" << Clock::is_steady << " nominal_tick_seconds="
                  << double(Clock::period::num) / Clock::period::den << '\n';
        std::vector<double> baseline(single_count);
        for (auto& ns : baseline) {
            const auto start = timestamp();
            const auto stop = timestamp();
            ns = std::chrono::duration<double, std::nano>(stop - start).count();
        }
        write(file, "cpp_timer_only", "baseline", "individual", baseline, 1);
        const auto d = [](const Case& c) -> const Input<double>& { return c.d; };
        const auto f = [](const Case& c) -> const Input<float>& { return c.f; };
        measure(file, "cpp_double_conditioner", data, conditioner_double, d);
        measure(file, "cpp_double_beta_only", data, beta_double, d);
        measure(file, "cpp_float_us_conditioner", data, conditioner_float, f);
        measure(file, "cpp_float_us_beta_only", data, beta_float, f);
        return 0;
    } catch (const std::exception& e) {
        std::cerr << e.what() << '\n';
        return 1;
    }
}
