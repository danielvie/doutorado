function run_relaxed_comparison()
%RUN_RELAXED_COMPARISON Regenerate all three cases and report tables locally.
study_dir = fileparts(mfilename('fullpath'));
output_root = fullfile(study_dir, 'results', 'relaxed-last-switch');
labels = { ...
    'Minimum applied dwell, $\mu\mathrm{s}$', 'Cycles with conditioning', ...
    'Cycles with $\beta<1$', 'Cycles with terminal extension', ...
    'First $\beta$', 'First-cycle duration, $\mu\mathrm{s}$', ...
    'Maximum cycle duration, $\mu\mathrm{s}$', 'Final cycle duration, $\mu\mathrm{s}$', ...
    'Sustained anchor crossing, cycle', 'Time at first anchor crossing, ms', ...
    'Sustained fixed-clock crossing, cycle', 'Final anchor error', ...
    'Final fixed-clock error', 'Total boundary displacement, $\mu\mathrm{s}$', ...
    'Elapsed time for 100 cycles, ms', 'Sum of squared sampled anchor errors'};
fields = {'minimum_dwell_us', 'conditioned_cycle_count', 'beta_active_cycle_count', ...
    'extended_cycle_count', 'first_beta', 'first_cycle_duration_us', ...
    'maximum_cycle_duration_us', 'final_cycle_duration_us', ...
    'sustained_anchor_cycle_below_001', 'time_to_anchor_001_ms', ...
    'sustained_global_cycle_below_001', 'final_phase_reset_error', ...
    'final_global_phase_error', 'total_boundary_delay_us', 'elapsed_time_ms', ...
    'cycle_sampled_squared_error_sum'};
formats = {'%.3f','%.0f','%.0f','%.0f','%.6f','%.6f','%.6f','%.6f', ...
    '%.0f','%.6f','%.0f','%.3g','%.6g','%.6f','%.6f','%.6f'};
for scale = 1:3
    output_dir = fullfile(output_root, sprintf('error-scale-%gx', scale));
    study = run_comparison(output_dir, scale);
    m = study.metrics;
    assert(isequal(m.sustained_anchor_cycle_below_001, m.first_anchor_cycle_below_001));
    if scale == 3
        % Regression against the handoff's full-precision 3x transcription.
        assert(abs(study.daniel_relaxed.beta(1) - 0.192046815252170) < 1e-10);
        assert(max(abs(study.daniel_relaxed.period(1:3)*1e6 - ...
            [304.401806440967;292.994304441994;286.377901423019])) < 1e-6);
        assert(abs(m.total_boundary_delay_us(2) - 25.77401230598) < 1e-6);
        assert(isequal(m.sustained_anchor_cycle_below_001, [12;12;7]));
    end
    fid = fopen(fullfile(output_dir, 'metrics_table.tex'), 'w');
    assert(fid >= 0, 'Cannot write report table.');
    cleanup = onCleanup(@() fclose(fid));
    fprintf(fid, '%% Generated by run_relaxed_comparison.m; do not edit.\n');
    fprintf(fid, '\\begin{tabular}{@{}lrrr@{}}\n\\toprule\n');
    fprintf(fid, 'Measure & \\texttt{daniel} & \\texttt{daniel-relaxed} & \\texttt{marcolino} \\\\\n\\midrule\n');
    for row = 1:numel(fields)
        fprintf(fid, '%s', labels{row});
        for method = 1:3
            value = m.(fields{row})(method);
            if isnan(value)
                if ismember(fields{row}, {'beta_active_cycle_count','first_beta'})
                    text = 'n/a';
                else
                    text = 'none';
                end
            else
                text = sprintf(formats{row}, value);
            end
            fprintf(fid, ' & %s', text);
        end
        fprintf(fid, ' \\\\\n');
    end
    fprintf(fid, '\\bottomrule\n\\end{tabular}\n');
    clear cleanup
end
fprintf('Three-case evidence and report tables: %s\n', output_root);
end
