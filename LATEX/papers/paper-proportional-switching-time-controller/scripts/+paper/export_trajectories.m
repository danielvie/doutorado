function trajectories = export_trajectories(paths, benchmark, model, response, long_response)
%EXPORT_TRAJECTORIES Publication version of the separate trajectory study.
% Reuse article states/actions; sample each physical mode with exact exponentials.
config = benchmark.config;
anchor = benchmark.orbit_anchor;
samples = benchmark.trajectory_samples_per_interval;
interval_count = numel(config.Omega);
per_cycle = samples * interval_count;
count = benchmark.cycle_count * per_cycle + 1;
time_on = zeros(count, 1); time_off = time_on;
state_on = zeros(count, 3); state_off = state_on;
for cycle = 1:benchmark.cycle_count
    [ton, xon] = paper.sample_cycle(config, response.conditioned_states(:, cycle), ...
        response.applied_offsets(:, cycle), samples);
    [toff, xoff] = paper.sample_cycle(config, response.open_loop_states(:, cycle), ...
        zeros(interval_count - 1, 1), samples);
    assert(norm(xon(end, :)' - response.conditioned_states(:, cycle + 1), inf) < 1e-11, ...
        'Dense conditioned propagation differs from cycle-start simulation.');
    assert(norm(xoff(end, :)' - response.open_loop_states(:, cycle + 1), inf) < 1e-11, ...
        'Dense open-loop propagation differs from cycle-start simulation.');
    rows = (cycle - 1) * per_cycle + (1:per_cycle + 1);
    time_on(rows) = (cycle - 1) * benchmark.period + ton;
    time_off(rows) = (cycle - 1) * benchmark.period + toff;
    state_on(rows, :) = xon; state_off(rows, :) = xoff;
end
[reference_time, reference_state] = paper.sample_cycle(config, anchor, ...
    zeros(interval_count - 1, 1), samples);
[final_time, final_state] = paper.sample_cycle(config, long_response.open_loop_states(:, end), ...
    zeros(interval_count - 1, 1), samples);
% Fixed-schedule affine propagation is exact at cycle starts. Allow accumulated
% roundoff from the repeated affine simulation and nominal closure residual.
error = benchmark.initial_state - anchor;
exact_error = zeros(benchmark.long_simulation_cycles + 1, 1);
for index = 1:numel(exact_error)
    exact_error(index) = norm(benchmark.state_scale \ error);
    error = model.Phi * error;
end
assert(max(abs(exact_error - long_response.open_loop_error)) < 1e-8, ...
    'Long-horizon affine propagation and exact nominal error map disagree.');
trajectories = struct('time_on', time_on, 'state_on', state_on, ...
    'time_off', time_off, 'state_off', state_off, ...
    'reference_time', reference_time, 'reference_state', reference_state, ...
    'final_time', final_time, 'final_state', final_state, ...
    'long_open_loop_states', long_response.open_loop_states, ...
    'long_open_loop_error', long_response.open_loop_error, ...
    'convergence_cycle', long_response.convergence_cycle, ...
    'samples_per_interval', samples);
save(fullfile(paths.results, 'publication_trajectories.mat'), 'trajectories');
writetable(table(time_on, state_on(:, 1), state_on(:, 2), state_on(:, 3), ...
    time_off, state_off(:, 1), state_off(:, 2), state_off(:, 3), ...
    'VariableNames', {'controlled_time_s', 'controlled_vc1_v', 'controlled_vc2_v', ...
    'controlled_il_a', 'open_time_s', 'open_vc1_v', 'open_vc2_v', 'open_il_a'}), ...
    fullfile(paths.results, 'continuous_trajectories.csv'));
% Keep plot and CSV samples sparse at long horizons; the MAT file retains all cycles.
cycles = unique([0:1000, round(logspace(3, log10(benchmark.long_simulation_cycles), 1500)), ...
    long_response.convergence_cycle + (-5:5), benchmark.long_simulation_cycles])';
cycles = cycles(cycles >= 0 & cycles <= benchmark.long_simulation_cycles);
x = long_response.open_loop_states(:, cycles + 1)';
writetable(table(cycles, cycles * benchmark.period, long_response.open_loop_error(cycles + 1), ...
    x(:, 1), x(:, 2), x(:, 3), 'VariableNames', ...
    {'cycle', 'time_s', 'normalized_error', 'vc1_v', 'vc2_v', 'il_a'}), ...
    fullfile(paths.results, 'open_loop_convergence.csv'));
paper.plot_trajectories(paths.article_figures, trajectories, benchmark);
end
