function benchmark = benchmark()
%BENCHMARK Published schedule, reconciliation, scales, and experiment settings.
% The physical converter dynamics remain owned by simulations/matlab-sim.
simulation = Simulation(Enums.SimName.PATINO_2);
config = simulation.m_config;
dynamics_indices = [1, 2, 4, 8, 3, 1, 5, 8, 5];
published_modes = [0, 1, 3, 7, 2, 0, 4, 7, 4];
corrected_boundary_us = [0, 63.889183506119, 87.556782881998, ...
    109.556782881998, 132.538059851499, 154.538059851499, ...
    218.210068109424, 240.380157440049, 263.827584831201, 286];
published_boundary_us = [0, 66, 88, 110, 132, 154, 220, 242, 264, 286];
published_anchor = [9.9247; 19.2928; 0.9823];
config.Omega = dynamics_indices;
config.Ts = corrected_boundary_us * 1e-6;
config.orbit_anchor = published_anchor;
config.x0 = published_anchor;

boundary_times = config.Ts(:);
nominal_dwell = diff(boundary_times);
period = boundary_times(end) - boundary_times(1);
benchmark_design_dwell_bound = 22e-6;
applied_schedule_dwell_bound = 3e-6;
max_published_boundary_correction = max(abs( ...
    corrected_boundary_us - published_boundary_us)) * 1e-6;
assert(isequal(config.Omega(:)', dynamics_indices), ...
    'The benchmark dynamics indices changed unexpectedly.');
assert(isequal(config.Omega(:)' - 1, published_modes), ...
    'The dynamics indices do not match the published physical modes.');
assert(numel(config.Omega) == 9 && numel(boundary_times) == 10, ...
    'The three-cell converter benchmark must contain exactly 9 intervals.');
assert(period == 286e-6, ...
    'The three-cell converter benchmark period must be exactly 286 us.');
assert(all(diff(corrected_boundary_us) >= 22), ...
    'A nominal benchmark dwell is below the 22 us design bound.');
assert(isequal(config.orbit_anchor(:), published_anchor) && ...
    isequal(config.x0(:), published_anchor), ...
    'Both benchmark initial-state fields must equal the published anchor.');

orbit_anchor = published_anchor;
state_scale = diag([10, 20, 1]);
timing_scale = 10e-6;
initial_state = [7.5143; 20.8211; 0.0314];
cycle_count = 100;
long_simulation_cycles = 100000;
aggressive_input_weight = 0.001;
conservative_input_weight = 0.1;

benchmark = struct( ...
    'config', config, ...
    'dynamics_indices', dynamics_indices, ...
    'published_modes', published_modes, ...
    'published_boundary_us', published_boundary_us, ...
    'orbit_anchor', orbit_anchor, ...
    'nominal_dwell', nominal_dwell, ...
    'period', period, ...
    'benchmark_design_dwell_bound', benchmark_design_dwell_bound, ...
    'applied_schedule_dwell_bound', applied_schedule_dwell_bound, ...
    'max_published_boundary_correction', max_published_boundary_correction, ...
    'state_scale', state_scale, ...
    'timing_scale', timing_scale, ...
    'initial_state', initial_state, ...
    'cycle_count', cycle_count, ...
    'long_simulation_cycles', long_simulation_cycles, ...
    'trajectory_samples_per_interval', 30, ...
    'aggressive_input_weight', aggressive_input_weight, ...
    'conservative_input_weight', conservative_input_weight);
end
