"""Export manuscript macros from saved Common-P study evidence, without solvers."""

import argparse
import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "studies/s2-kawa-synthesis/results"
OUTPUT = ROOT / "latex/common_p_study.tex"
METHODS = (("kawa_decay", r"Common-$P$"), ("current", "Conditioned LQR"),
           ("mpc5", "MPC-5"))


def read_rows(name):
    with (RESULTS / name).open(encoding="utf-8-sig", newline="") as handle:
        return list(csv.DictReader(handle))


def render():
    synthesis = json.loads((RESULTS / "synthesis.json").read_text(encoding="utf-8"))
    decay = synthesis["candidates"]["decay"]
    summary = {(row["method"], int(row["error_scale"])): row
               for row in read_rows("summary.csv")}
    timing = {row["method"]: row for row in read_rows("timing.csv")}
    initial = next(row for row in read_rows("history.csv")
                   if row["method"] == "kawa_decay" and int(row["error_scale"]) == 1)
    assert int(initial["cycle"]) == 0

    # Certificate eigenvalues are already saved from full-precision matrices.
    macros = {
        "CommonPRate": f"{decay['rate']:.12f}",  # Contraction rate, not its square.
        "CommonPOpenRadius": f"{decay['analytical_rate_floor']:.12f}",
        "CommonPRawRadius": f"{decay['raw_radius']:.12f}",
        "CommonPMinEigenvalue": f"{decay['min_eigenvalue_P']:.12f}",
        "CommonPEndpointZeroDecrease": f"{decay['endpoint_decreases'][0]:.12f}",
        "CommonPEndpointOneDecrease": f"{decay['endpoint_decreases'][1]:.12f}",
        "CommonPMinRawDwell": f"{float(summary['kawa_decay', 1]['minimum_raw_dwell_us']):.6f}",
        "CommonPInitialBeta": f"{float(initial['beta']):.9f}",
    }
    lines = [
        "% Generated by scripts/export_common_p_study.py from saved s2-kawa-synthesis evidence.",
        "% Raw minimum dwell (microseconds) and initial beta refer to the 1x Common-P run.",
        "% Endpoint decreases are minimum eigenvalues of P - M^T P M, not rate residuals.",
    ]
    lines += [rf"\providecommand{{\{name}}}{{{value}}}" for name, value in macros.items()]
    tracking, timings = [], []
    for method, label in METHODS:
        values = []
        for scale in (1, 2, 3):
            row = summary[method, scale]
            cycle = float(row["sustained_cycle_below_001"])
            assert cycle.is_integer()
            values += [str(int(cycle)), f"{float(row['evaluation_cost']):.6f}"]
        tracking.append(" & ".join([label, *values]) + r" \\")
        row = timing[method]
        timings.append(" & ".join([label, f"{float(row['median_us']):.2f}",
                                   f"{float(row['p95_us']):.2f}"]) + r" \\")
    for name, rows in (("CommonPTrackingRows", tracking), ("CommonPTimingRows", timings)):
        lines += [rf"\providecommand{{\{name}}}{{%", *rows, "}"]
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="check the saved export without writing")
    args = parser.parse_args()
    content = render()
    if args.check:
        if OUTPUT.read_bytes() != content.encode("utf-8"):
            parser.exit(1, f"Stale export: {OUTPUT}\n")
        print("Common-P manuscript export matches saved evidence.")
    else:
        OUTPUT.write_bytes(content.encode("utf-8"))
        print(f"Wrote {OUTPUT}")


if __name__ == "__main__":
    main()
